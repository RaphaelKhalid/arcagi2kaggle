"""Assemble the ARC Prize 2026 submission notebook from ``kaggle_notebook/src``.

Usage:
    python kaggle_notebook/build_notebook.py            # (re)write notebook.ipynb
    python kaggle_notebook/build_notebook.py --check    # verify notebook.ipynb is up to date

The modules under ``src/`` are the single source of truth for every
``%%writefile`` cell.  The notebook-level switches live in ``PROFILE`` below;
the builder rewrites the matching ``FLAG = ...`` lines of the emitted module
cells so the notebook and ``PROFILE`` can never disagree, and refuses to build
when the ``src/`` defaults drift from ``PROFILE`` (the local tests import the
``src/`` modules directly, so both must say the same thing).

``kernel-metadata.json`` is validated against the profile: the Qwen2.5-Coder
model source must be attached exactly when Leg C is enabled.
"""

